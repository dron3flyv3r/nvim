local M = {}

--- Bumped whenever `SCRIPT` changes in a way Neovim depends on. The bridge
--- writes it into `state.json`, so an editor still running last week's script
--- is told to reinstall rather than silently misreporting.
M.VERSION = 1

--- A top-level folder on purpose: it adds no entry to any tracked file, which
--- an embedded package under `Packages/` would.
M.FOLDER = "Assets/NvimBridge"

local EXCLUDES = { M.FOLDER .. "/", M.FOLDER .. ".meta" }

---@param root string
---@return string
function M.dir(root) return root .. "/" .. M.FOLDER .. "/Editor" end

---@param root string
---@return string
function M.watch_dir(root) return root .. "/Library/nvim-unity" end

---@param root string
---@return string
function M.state_file(root) return M.watch_dir(root) .. "/state.json" end

---@param root string
---@return string
function M.diagnostics_file(root) return M.watch_dir(root) .. "/diagnostics.json" end

---@param root string
---@return boolean
function M.installed(root) return vim.fn.filereadable(M.dir(root) .. "/NvimBridge.cs") == 1 end

local ASMDEF = [==[{
